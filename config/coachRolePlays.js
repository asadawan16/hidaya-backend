// Hidaya's "Quran Tutor English Role-Play Practice Book" (Teacher + Student
// versions), word for word, for the English Coach's scripted practice.
//
// The book is printed as a two-column table per role play: the teacher's line
// in one column and the student's (or parent's) line in the other. Each row is
// not always "teacher, then reply" — in some role plays the student speaks
// first ("Teacher, may I get some water?") — so the lines below are written
// out in the order the conversation actually runs. The wording is the book's
// and must not be paraphrased: tutors have drilled these exact sentences.
//
//   T — the teacher: the tester says this line (the book's English). The
//       third item is the Teacher Version's Urdu prompt for it, shown instead
//       of the English in Urdu mode (CoachSettings.scriptMode)
//   S — the student (Ahmad, or the play's `student`)
//   P — the parent (Unit 9 and the last mock class)
//
// Where the book has the teacher say two lines with no reply between them,
// they are joined into one line, which is how they are said on a call (their
// two Urdu prompts are joined the same way).
//
// The Urdu was extracted from the Teacher Version PDF (Jameel Noori
// Nastaleeq: each ligature's letters are stored reversed and had to be put
// back in order) and checked line by line against the English.
//
// This file is the STARTING SET only: the first time the coach is used the
// eleven units are copied into the CoachScript collection
// (services/coachScripts.js#ensureBookScripts), where admins edit them on the
// Scripts tab. It is still what "Restore the book's wording" goes back to.
//
// A scripted call is one Unit ("Part") of the book. The AI never writes the
// character's words: the server plays the next S / P line after the tester
// says the T line (controllers/portalCoachController.js, matching in
// utils/coachScript.js).

